#!/usr/bin/env python3
"""Writes the simulator's G1 with Inspire RH56DFQ hands, from the URDF MoveIt plans against.

Reads g1_description's Inspire URDF and the simulator's Dex3 model, g1_29dof.xml, and writes
g1_29dof_inspire.xml beside it in the unitree_mujoco checkout: the same robot with each Dex3
subtree replaced by the Inspire hand. Bodies, inertias, joint axes and ranges come from the URDF,
the six coupled joints become joint equalities, and each phalanx gets a contact capsule fitted to
its mesh. Deterministic, so a rerun shows a diff only when the URDF or the meshes change.

    python3 workspace/src/g1_bringup/tools/inspire_hand_mjcf.py

Python because it is offline tooling that reads XML and meshes; it runs nowhere in the stack.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import xml.etree.ElementTree as ET

import numpy as np

WORKSPACE = pathlib.Path(__file__).resolve().parents[3]
URDF = WORKSPACE / "src/g1_description/urdf/g1_29dof_rev_1_0_with_inspire_hand_DFQ.urdf"
MODEL_DIR = WORKSPACE / "vendor/unitree_mujoco/unitree_robots/g1"

SIDES = (("left", "L"), ("right", "R"))

# Phalanx capsules: the radius is this share of the mesh's spread across the long axis, and the
# ends are pulled in by the radius, so the capsule sits inside the shell rather than around it.
CAPSULE_RADIUS_QUANTILE = 0.80
# The palm's box covers the mesh beyond the wrist flange: this far from the base origin, along the
# finger axis (-y in the hand base frame), and on.
PALM_START_M = 0.035
# Digits whose contact with their own palm is ignored (the palm's direct children are already).
PALM_EXCLUDED_DIGITS = (
    "thumb_proximal",
    "thumb_intermediate",
    "thumb_distal",
    "index_intermediate",
    "middle_intermediate",
    "ring_intermediate",
    "pinky_intermediate",
)
# Equality stiffness for the coupled joints, s: a linkage, so stiff, but at least two steps of the
# simulator's 2 ms.
COUPLING_SOLREF = "0.005 1"

HEADER = (
    " Generated by grove-g1's g1_bringup/tools/inspire_hand_mjcf.py from g1_description's\n"
    "     g1_29dof_rev_1_0_with_inspire_hand_DFQ.urdf (Unitree's G1 with Inspire RH56DFQ hands) and\n"
    "     g1_29dof.xml; rerun it rather than editing this file. "
)

DEFAULTS = """
<default>
  <!-- Inspire RH56DFQ joints. No <actuator> and no <sensor> entries, as for the Dex3: the SDK
       bridge sizes itself from nu, so inspire_handler drives the six actuated joints through
       qfrc_applied, and the six coupled ones follow through joint equalities. -->
  <default class="inspire_motor">
    <joint damping="0.02" armature="0.001" frictionloss="0.01"/>
  </default>
  <default class="inspire_visual">
    <geom type="mesh" contype="0" conaffinity="0" group="1" density="0" rgba="0.85 0.85 0.85 1"/>
  </default>
  <!-- Contact like the Dex3's: bit 2 pairs with nothing but the props a manipulation scene opts in,
       group 3 stays out of the viewer and the cameras, priority wins over the object's contact
       parameters, condim 4 adds the torsional friction a pad has. -->
  <default class="inspire_collision">
    <geom contype="2" conaffinity="2" group="3" density="0" condim="4" priority="1"
          friction="1 0.02 0.0001" solref="0.006 1" solimp="0.95 0.99 0.001"/>
  </default>
</default>
"""


def _floats(text: str | None, count: int = 3) -> list[float]:
    return [float(v) for v in (text or " ".join(["0"] * count)).split()]


def _fmt(values) -> str:
    return " ".join(f"{v:.6g}" if abs(v) >= 1e-12 else "0" for v in values)


def _rpy_quat(rpy: list[float]) -> list[float]:
    """URDF fixed-axis roll, pitch, yaw as a MuJoCo w, x, y, z quaternion."""
    r, p, y = (a / 2.0 for a in rpy)
    cr, sr, cp, sp, cy, sy = (
        math.cos(r),
        math.sin(r),
        math.cos(p),
        math.sin(p),
        math.cos(y),
        math.sin(y),
    )
    return [
        cr * cp * cy + sr * sp * sy,
        sr * cp * cy - cr * sp * sy,
        cr * sp * cy + sr * cp * sy,
        cr * cp * sy - sr * sp * cy,
    ]


def _rpy_matrix(rpy: list[float]) -> np.ndarray:
    r, p, y = rpy
    rx = np.array([[1, 0, 0], [0, math.cos(r), -math.sin(r)], [0, math.sin(r), math.cos(r)]])
    ry = np.array([[math.cos(p), 0, math.sin(p)], [0, 1, 0], [-math.sin(p), 0, math.cos(p)]])
    rz = np.array([[math.cos(y), -math.sin(y), 0], [math.sin(y), math.cos(y), 0], [0, 0, 1]])
    return rz @ ry @ rx


def _stl_vertices(path: pathlib.Path) -> np.ndarray:
    """The vertices of a binary STL, n x 3, in its own frame."""
    data = path.read_bytes()
    count = int.from_bytes(data[80:84], "little")
    record = np.dtype([("normal", "<f4", 3), ("v", "<f4", (3, 3)), ("attr", "<u2")])
    triangles = np.frombuffer(data, dtype=record, count=count, offset=84)
    return triangles["v"].reshape(-1, 3).astype(np.float64)


def _capsule(vertices: np.ndarray) -> tuple[np.ndarray, np.ndarray, float]:
    """A capsule along the mesh's principal axis: its two end points and its radius."""
    centre = vertices.mean(axis=0)
    _, _, axes = np.linalg.svd(vertices - centre, full_matrices=False)
    axis = axes[0]
    along = (vertices - centre) @ axis
    across = np.linalg.norm((vertices - centre) - np.outer(along, axis), axis=1)
    radius = float(np.quantile(across, CAPSULE_RADIUS_QUANTILE))
    low, high = along.min() + radius, along.max() - radius
    if high <= low:
        low = high = (along.min() + along.max()) / 2.0
    return centre + low * axis, centre + high * axis, radius


class Urdf:
    """The Inspire hands' links and joints, by name."""

    def __init__(self, path: pathlib.Path) -> None:
        root = ET.parse(path).getroot()
        self.links = {link.get("name"): link for link in root.findall("link")}
        self.joints = list(root.findall("joint"))
        self.children: dict[str, list[ET.Element]] = {}
        for joint in self.joints:
            self.children.setdefault(joint.find("parent").get("link"), []).append(joint)


def _mesh_name(link: ET.Element) -> str | None:
    mesh = link.find("visual/geometry/mesh")
    return pathlib.Path(mesh.get("filename")).stem if mesh is not None else None


def _body(urdf: Urdf, joint: ET.Element, model_dir: pathlib.Path, meshes: list[str]) -> ET.Element:
    """The MJCF body for the child link of a URDF joint, with its subtree."""
    name = joint.find("child").get("link")
    link = urdf.links[name]
    origin = joint.find("origin")
    body = ET.Element(
        "body",
        name=name,
        pos=_fmt(_floats(origin.get("xyz"))),
        quat=_fmt(_rpy_quat(_floats(origin.get("rpy")))),
    )
    inertial = link.find("inertial")
    inertia = inertial.find("inertia")
    ET.SubElement(
        body,
        "inertial",
        pos=_fmt(_floats(inertial.find("origin").get("xyz"))),
        mass=f"{float(inertial.find('mass').get('value')):.6g}",
        fullinertia=_fmt(float(inertia.get(k)) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")),
    )
    if joint.get("type") == "revolute":
        limit = joint.find("limit")
        ET.SubElement(
            body,
            "joint",
            name=joint.get("name"),
            axis=_fmt(_floats(joint.find("axis").get("xyz"))),
            range=_fmt([float(limit.get("lower")), float(limit.get("upper"))]),
            attrib={"class": "inspire_motor"},
        )
    mesh = _mesh_name(link)
    if mesh is not None:
        meshes.append(mesh)
        visual = link.find("visual/origin")
        rotation = _rpy_matrix(_floats(visual.get("rpy") if visual is not None else None))
        offset = np.array(_floats(visual.get("xyz") if visual is not None else None))
        ET.SubElement(body, "geom", mesh=mesh, attrib={"class": "inspire_visual"})
        vertices = _stl_vertices(model_dir / "meshes" / f"{mesh}.STL") @ rotation.T + offset
        if name.endswith("hand_base_link"):
            # The palm, past the wrist flange, as a box.
            palm = vertices[vertices[:, 1] < -PALM_START_M]
            low, high = palm.min(axis=0), palm.max(axis=0)
            ET.SubElement(
                body,
                "geom",
                type="box",
                pos=_fmt((low + high) / 2.0),
                size=_fmt((high - low) / 2.0),
                attrib={"class": "inspire_collision"},
            )
        elif len(vertices) > 3000:
            # Phalanges only: the thumb's small yaw link carries no contact surface.
            start, end, radius = _capsule(vertices)
            ET.SubElement(
                body,
                "geom",
                type="capsule",
                fromto=_fmt([*start, *end]),
                size=f"{radius:.4g}",
                attrib={"class": "inspire_collision"},
            )
    for child in urdf.children.get(name, []):
        body.append(_body(urdf, child, model_dir, meshes))
    return body


def _without_dex3(root: ET.Element) -> None:
    """Drops every Dex3 body, mesh, default, contact exclusion and the comments about them."""
    for parent in root.iter():
        for child in list(parent):
            name = child.get("name") or child.get("body1") or ""
            text = child.text or ""
            is_comment = child.tag is ET.Comment
            if (
                (not is_comment and "_hand_" in name)
                or child.get("class", "").startswith("dex3")
                or (is_comment and "Dex3" in text)
                or (is_comment and "thumb_1 sits inside" in text)
            ):
                parent.remove(child)


def build(urdf_path: pathlib.Path, model_dir: pathlib.Path) -> ET.ElementTree:
    """The Inspire model, from the URDF and the Dex3 model beside it."""
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    tree = ET.parse(model_dir / "g1_29dof.xml", parser=parser)
    root = tree.getroot()
    root.set("model", "g1_29dof_inspire")
    _without_dex3(root)

    urdf = Urdf(urdf_path)
    meshes: list[str] = []
    for side, _ in SIDES:
        wrist = root.find(f".//body[@name='{side}_wrist_yaw_link']")
        mount = next(j for j in urdf.children[f"{side}_wrist_yaw_link"] if j.get("type") == "fixed")
        wrist.append(_body(urdf, mount, model_dir, meshes))

    asset = root.find("asset")
    for mesh in meshes:
        ET.SubElement(asset, "mesh", name=mesh, file=f"{mesh}.STL")

    default = root.find("default")
    for element in ET.fromstring(
        DEFAULTS, parser=ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    ):
        default.append(element)

    equality = root.find("equality")
    if equality is None:
        equality = ET.SubElement(root, "equality")
    equality.append(
        ET.Comment(
            " The hand's linkages: each coupled joint follows its actuated one, as the URDF's"
            " <mimic> tags say. "
        )
    )
    for joint in urdf.joints:
        mimic = joint.find("mimic")
        if mimic is None:
            continue
        coef = [float(mimic.get("offset", "0")), float(mimic.get("multiplier", "1")), 0, 0, 0]
        ET.SubElement(
            equality,
            "joint",
            name=f"{joint.get('name')}_coupling",
            joint1=joint.get("name"),
            joint2=mimic.get("joint"),
            polycoef=_fmt(coef),
            solref=COUPLING_SOLREF,
        )

    contact = root.find("contact")
    if contact is None:
        contact = ET.SubElement(root, "contact")
    contact.append(
        ET.Comment(
            " The palm box is fuller than the real palm face, so a closing finger or a bending thumb"
            " would stall on it with nothing held, which the grip check reads as an object. Fingers"
            " still meet the thumb, and anything the scene opts in. "
        )
    )
    for _, prefix in SIDES:
        for digit in PALM_EXCLUDED_DIGITS:
            ET.SubElement(
                contact, "exclude", body1=f"{prefix}_hand_base_link", body2=f"{prefix}_{digit}"
            )

    root.insert(0, ET.Comment(HEADER))
    ET.indent(tree, space="  ")
    return tree


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--urdf", type=pathlib.Path, default=URDF)
    parser.add_argument("--model-dir", type=pathlib.Path, default=MODEL_DIR)
    args = parser.parse_args()
    tree = build(args.urdf, args.model_dir)
    out = args.model_dir / "g1_29dof_inspire.xml"
    tree.write(out, encoding="unicode")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
